SELECT
    Z.ZONE_NAME,
    SUM(PT.TAX_AMOUNT) AS TOTAL_TAX
FROM ZONE Z
JOIN CITIZEN C
ON Z.ZONE_ID = C.ZONE_ID
JOIN PROPERTY P
ON C.CITIZEN_ID = P.CITIZEN_ID
JOIN PROPERTY_TAX PT
ON P.PROPERTY_ID = PT.PROPERTY_ID
WHERE PT.PAYMENT_STATUS = 'Paid'
GROUP BY Z.ZONE_ID, Z.ZONE_NAME
HAVING SUM(PT.TAX_AMOUNT) =
(
    SELECT MAX(TOTAL_TAX)
    FROM
    (
        SELECT SUM(PT2.TAX_AMOUNT) AS TOTAL_TAX
        FROM PROPERTY_TAX PT2
        WHERE PT2.PAYMENT_STATUS = 'Paid'
        GROUP BY PT2.PROPERTY_ID
    ) X
);

