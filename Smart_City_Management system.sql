SELECT
    Z.ZONE_NAME,
    SUM(W.MONTHLY_CONSUMPTION) AS TOTAL_WATER_CONSUMPTION,
    AVG(W.MONTHLY_CONSUMPTION) AS AVG_WATER_CONSUMPTION,
    SUM(W.BILL_AMOUNT) AS TOTAL_WATER_BILL
FROM WATER_CONNECTION W
JOIN PROPERTY P
ON W.PROPERTY_ID = P.PROPERTY_ID
JOIN CITIZEN C
ON P.CITIZEN_ID = C.CITIZEN_ID
JOIN ZONE Z
ON C.ZONE_ID = Z.ZONE_ID
GROUP BY Z.ZONE_ID, Z.ZONE_NAME
ORDER BY TOTAL_WATER_CONSUMPTION DESC;

SELECT
    Z.ZONE_NAME,
    SUM(E.MONTHLY_UNITS) AS TOTAL_UNITS,
    AVG(E.MONTHLY_UNITS) AS AVG_UNITS,
    SUM(E.BILL_AMOUNT) AS TOTAL_ELECTRICITY_BILL
FROM ELECTRICITY_CONNECTION E
JOIN PROPERTY P
ON E.PROPERTY_ID = P.PROPERTY_ID
JOIN CITIZEN C
ON P.CITIZEN_ID = C.CITIZEN_ID
JOIN ZONE Z
ON C.ZONE_ID = Z.ZONE_ID
GROUP BY Z.ZONE_ID, Z.ZONE_NAME
ORDER BY TOTAL_UNITS DESC;

