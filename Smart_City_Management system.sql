CREATE VIEW CITIZEN_PROFILE_VIEW AS
SELECT
    C.CITIZEN_ID,
    C.CITIZEN_NAME,
    Z.ZONE_NAME,
    P.PROPERTY_TYPE,
    P.PROPERTY_ADDRESS,
    P.PROPERTY_VALUE
FROM CITIZEN C
JOIN ZONE Z
ON C.ZONE_ID = Z.ZONE_ID
LEFT JOIN PROPERTY P
ON C.CITIZEN_ID = P.CITIZEN_ID;

SELECT * FROM CITIZEN_PROFILE_VIEW;

CREATE VIEW TAX_COLLECTION_VIEW AS
SELECT
    Z.ZONE_NAME,
    SUM(PT.TAX_AMOUNT) AS TOTAL_TAX_COLLECTED
FROM ZONE Z
JOIN CITIZEN C
ON Z.ZONE_ID = C.ZONE_ID
JOIN PROPERTY P
ON C.CITIZEN_ID = P.CITIZEN_ID
JOIN PROPERTY_TAX PT
ON P.PROPERTY_ID = PT.PROPERTY_ID
WHERE PT.PAYMENT_STATUS = 'Paid'
GROUP BY Z.ZONE_ID, Z.ZONE_NAME;

SELECT * FROM TAX_COLLECTION_VIEW;

CREATE VIEW COMPLAINT_STATUS_VIEW AS
SELECT
    C.CITIZEN_NAME,
    CP.COMPLAINT_TYPE,
    CP.STATUS AS COMPLAINT_STATUS
FROM CITIZEN C
JOIN COMPLAINT CP
ON C.CITIZEN_ID = CP.CITIZEN_ID;

SELECT * FROM COMPLAINT_STATUS_VIEW;

