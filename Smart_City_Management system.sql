CREATE TABLE CITIZEN (
    CITIZEN_ID INT PRIMARY KEY,
    CITIZEN_NAME VARCHAR(100) NOT NULL,
    DATE_OF_BIRTH DATE,
    GENDER VARCHAR(10),
    MOBILE_NUMBER VARCHAR(15) UNIQUE,
    EMAIL VARCHAR(100) UNIQUE,
    AADHAAR_NUMBER VARCHAR(12) UNIQUE,
    ZONE_ID INT,

    CONSTRAINT FK_CITIZEN_ZONE
        FOREIGN KEY (ZONE_ID)
        REFERENCES ZONE(ZONE_ID),

    CONSTRAINT CHK_CITIZEN_GENDER
        CHECK (GENDER IN ('Male','Female','Other'))
);

CREATE TABLE PROPERTY (
    PROPERTY_ID INT PRIMARY KEY,
    CITIZEN_ID INT,
    PROPERTY_TYPE VARCHAR(20),
    PROPERTY_ADDRESS VARCHAR(300),
    PROPERTY_VALUE DECIMAL(15,2),

    CONSTRAINT FK_PROPERTY_CITIZEN
        FOREIGN KEY (CITIZEN_ID)
        REFERENCES CITIZEN(CITIZEN_ID),

    CONSTRAINT CHK_PROPERTY_VALUE
        CHECK (PROPERTY_VALUE > 0),

    CONSTRAINT CHK_PROPERTY_TYPE
        CHECK (PROPERTY_TYPE IN
        ('Residential','Commercial','Industrial'))
);

CREATE TABLE PROPERTY_TAX (
    TAX_ID INT PRIMARY KEY,
    PROPERTY_ID INT,
    TAX_YEAR YEAR,
    TAX_AMOUNT DECIMAL(15,2),
    PAYMENT_STATUS VARCHAR(20),

    CONSTRAINT FK_TAX_PROPERTY
        FOREIGN KEY (PROPERTY_ID)
        REFERENCES PROPERTY(PROPERTY_ID),

    CONSTRAINT CHK_TAX_AMOUNT
        CHECK (TAX_AMOUNT > 0),

    CONSTRAINT CHK_PAYMENT_STATUS
        CHECK (PAYMENT_STATUS IN ('Paid','Pending'))
);

CREATE TABLE WATER_CONNECTION (
    CONNECTION_ID INT PRIMARY KEY,
    PROPERTY_ID INT,
    METER_NUMBER VARCHAR(30) UNIQUE,
    MONTHLY_CONSUMPTION DECIMAL(10,2),
    BILL_AMOUNT DECIMAL(12,2),

    CONSTRAINT FK_WATER_PROPERTY
        FOREIGN KEY (PROPERTY_ID)
        REFERENCES PROPERTY(PROPERTY_ID),

    CONSTRAINT CHK_WATER_CONSUMPTION
        CHECK (MONTHLY_CONSUMPTION >= 0),

    CONSTRAINT CHK_WATER_BILL
        CHECK (BILL_AMOUNT >= 0)
);

CREATE TABLE ELECTRICITY_CONNECTION (
    CONNECTION_ID INT PRIMARY KEY,
    PROPERTY_ID INT,
    METER_NUMBER VARCHAR(30) UNIQUE,
    MONTHLY_UNITS DECIMAL(10,2),
    BILL_AMOUNT DECIMAL(12,2),

    CONSTRAINT FK_ELECTRICITY_PROPERTY
        FOREIGN KEY (PROPERTY_ID)
        REFERENCES PROPERTY(PROPERTY_ID),

    CONSTRAINT CHK_ELECTRICITY_UNITS
        CHECK (MONTHLY_UNITS >= 0),

    CONSTRAINT CHK_ELECTRICITY_BILL
        CHECK (BILL_AMOUNT >= 0)
);

CREATE TABLE WASTE_COLLECTION (
    COLLECTION_ID INT PRIMARY KEY,
    ZONE_ID INT,
    COLLECTION_DATE DATE,
    WASTE_QUANTITY DECIMAL(10,2),

    CONSTRAINT FK_WASTE_ZONE
        FOREIGN KEY (ZONE_ID)
        REFERENCES ZONE(ZONE_ID),

    CONSTRAINT CHK_WASTE_QUANTITY
        CHECK (WASTE_QUANTITY > 0)
);

CREATE TABLE COMPLAINT (
    COMPLAINT_ID INT PRIMARY KEY,
    CITIZEN_ID INT,
    COMPLAINT_TYPE VARCHAR(100),
    COMPLAINT_DESCRIPTION VARCHAR(500),
    COMPLAINT_DATE DATE,
    RESOLUTION_DATE DATE,
    STATUS VARCHAR(20),

    CONSTRAINT FK_COMPLAINT_CITIZEN
        FOREIGN KEY (CITIZEN_ID)
        REFERENCES CITIZEN(CITIZEN_ID),

    CONSTRAINT CHK_COMPLAINT_STATUS
        CHECK (STATUS IN ('Open','In Progress','Resolved'))
);

CREATE TABLE TRAFFIC_VIOLATION (
    VIOLATION_ID INT PRIMARY KEY,
    CITIZEN_ID INT,
    VEHICLE_NUMBER VARCHAR(20),
    VIOLATION_TYPE VARCHAR(100),
    FINE_AMOUNT DECIMAL(10,2),

    CONSTRAINT FK_VIOLATION_CITIZEN
        FOREIGN KEY (CITIZEN_ID)
        REFERENCES CITIZEN(CITIZEN_ID),

    CONSTRAINT CHK_FINE_AMOUNT
        CHECK (FINE_AMOUNT > 0)
);

CREATE TABLE SERVICE_REQUEST (
    REQUEST_ID INT PRIMARY KEY,
    CITIZEN_ID INT,
    SERVICE_TYPE VARCHAR(100),
    REQUEST_DATE DATE,
    REQUEST_STATUS VARCHAR(20),

    CONSTRAINT FK_REQUEST_CITIZEN
        FOREIGN KEY (CITIZEN_ID)
        REFERENCES CITIZEN(CITIZEN_ID),

    CONSTRAINT CHK_REQUEST_STATUS
        CHECK (REQUEST_STATUS IN
        ('Pending','Approved','Rejected','Completed'))
);

CREATE TABLE EMPLOYEE (
    EMPLOYEE_ID INT PRIMARY KEY,
    EMPLOYEE_NAME VARCHAR(100) NOT NULL,
    DEPARTMENT VARCHAR(100),
    SALARY DECIMAL(12,2),
    MANAGER_ID INT,

    CONSTRAINT CHK_EMPLOYEE_SALARY
        CHECK (SALARY > 0),

    CONSTRAINT FK_EMPLOYEE_MANAGER
        FOREIGN KEY (MANAGER_ID)
        REFERENCES EMPLOYEE(EMPLOYEE_ID)
);

